/* fontloom.com — the kaomoji and symbol catalogue.

   The single source of truth for /kaomoji/ and /symbols/. Every entry is
   `{ char, name, keywords }`: the literal characters, a name a human would
   recognise it by, and the words somebody would type into the filter box
   looking for it. Nothing here is computed — a kaomoji is a string of
   characters and pretending otherwise only adds a place for it to go wrong.

   The browser never loads this file. `tools/build_character_pages.py` reads it
   through `tools/dump_characters.js` and bakes every card into the static HTML
   of its page, the same way the style pages bake their character maps: a picker
   whose only content is an empty grid waiting on JavaScript is not a page, and
   shipping forty kilobytes of data to render markup that could have been
   written at build time costs every visitor on every page. It stays under
   assets/js/ because it is site data and `test/characters.test.js` requires it
   from Node.

   Two rules, both learned the hard way:

   - **Everything must render with the fonts a device already has.** No webfont
     is loaded anywhere on this site, so a character that needs one arrives as
     a tofu box. `tools/check_glyphs.mjs` renders every entry in real Chrome and
     fails on anything that paints identically to an unassigned code point.
   - **Backslashes are literal.** `¯\_(ツ)_/¯` is the most-copied kaomoji there
     is and it is one escaping mistake away from `¯_(ツ)_/¯`, which is wrong and
     looks nearly right. The test asserts that one byte for byte. */

